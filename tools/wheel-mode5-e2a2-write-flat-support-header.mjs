import { writeFile } from 'node:fs/promises';
import { loadOwnerM6TireGeometryR3 } from './owner-vehicle/owner-m6-tire-geometry-r3.mjs';

const outputPath = process.argv[2];
if (!outputPath) throw new Error('usage: node wheel-mode5-e2a2-write-flat-support-header.mjs <output.h>');

const STATION_COUNT = 129;
const tire = await loadOwnerM6TireGeometryR3();
if (tire.provenance.triangleCount !== 396 || tire.provenance.markerContract !== 'VERIFIED') {
  throw new Error(`Tire provenance drifted: ${JSON.stringify(tire.provenance)}`);
}

const stations = Array.from({ length: STATION_COUNT }, (_, i) => {
  const t = i / (STATION_COUNT - 1);
  const axial = tire.bounds.axialMin + tire.bounds.axialWidth * t;
  const radius = tire.outerRadiusP75At(axial);
  if (!Number.isFinite(radius)) throw new Error(`invalid P75 at station ${i}`);
  return { i, axial, radius };
});

const maxRadius = Math.max(...stations.map((s) => s.radius));
// Source-space plateau, before native float rounding. The tolerance is only to
// absorb JS arithmetic noise; it is orders of magnitude below Box3D slop and
// below the measured E1c faceting range.
const plateau = stations.filter((s) => Math.abs(s.radius - maxRadius) <= 1e-12);
if (plateau.length < 2) throw new Error(`P75 flat support plateau disappeared: ${JSON.stringify({ maxRadius, plateau })}`);
const left = plateau[0];
const right = plateau.at(-1);
if (!(left.axial < right.axial)) throw new Error('degenerate P75 flat support segment');

const cFloat = (v) => `${Number(v).toPrecision(17)}f`;
const sourceCommit = tire.provenance.sourceAuthority?.sourceAuthorityCommit ?? 'unknown';
const header = `// Generated by tools/wheel-mode5-e2a2-write-flat-support-header.mjs\n// Diagnostic-only E2a2 broad-ground support segment. Not a full tire shape.\n#pragma once\n\nstatic constexpr int E2A2_FLAT_LEFT_STATION = ${left.i};\nstatic constexpr int E2A2_FLAT_RIGHT_STATION = ${right.i};\nstatic constexpr float E2A2_FLAT_AXIAL_MIN = ${cFloat(left.axial)};\nstatic constexpr float E2A2_FLAT_AXIAL_MAX = ${cFloat(right.axial)};\nstatic constexpr float E2A2_FLAT_RADIUS = ${cFloat(maxRadius)};\nstatic constexpr const char* E2A2_SOURCE_AUTHORITY_COMMIT = "${sourceCommit}";\n`;
await writeFile(outputPath, header, 'utf8');

console.log('E2A2_FLAT_SUPPORT_HEADER', JSON.stringify({
  outputPath,
  left,
  right,
  maxRadius,
  plateauStationCount: plateau.length,
  provenance: tire.provenance,
}));
console.log('E2A2_FLAT_SUPPORT_HEADER_OK');
