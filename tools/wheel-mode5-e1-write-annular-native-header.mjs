import { writeFile } from 'node:fs/promises';
import { loadOwnerM6TireGeometryR3 } from './owner-vehicle/owner-m6-tire-geometry-r3.mjs';

const outputPath = process.argv[2];
if (!outputPath) throw new Error('usage: node wheel-mode5-e1-write-annular-native-header.mjs <output.h>');

const STATION_COUNT = 129;
const tire = await loadOwnerM6TireGeometryR3();
if (tire.provenance.triangleCount !== 396 || tire.provenance.markerContract !== 'VERIFIED') {
  throw new Error(`Tire provenance drifted: ${JSON.stringify(tire.provenance)}`);
}

const stations = [];
for (let i = 0; i < STATION_COUNT; i += 1) {
  const t = i / (STATION_COUNT - 1);
  const axial = tire.bounds.axialMin + tire.bounds.axialWidth * t;
  const interval = tire.radialIntervalAt(axial);
  const outer = tire.outerRadiusP75At(axial);
  if (!interval || !Number.isFinite(outer) || !(outer > interval.innerRadius)) {
    throw new Error(`invalid E1 station ${JSON.stringify({ i, axial, interval, outer })}`);
  }
  stations.push({ axial, inner: interval.innerRadius, outer });
}

function cFloat(value) {
  if (!Number.isFinite(value)) throw new Error(`non-finite C float ${value}`);
  return `${Number(value).toPrecision(17)}f`;
}
function emitArray(name, field) {
  const rows = stations.map((station, index) => {
    const suffix = index + 1 === stations.length ? '' : ',';
    return `    ${cFloat(station[field])}${suffix}`;
  });
  return `static constexpr float ${name}[E1_ANNULAR_STATION_COUNT] = {\n${rows.join('\n')}\n};`;
}

const sourceCommit = tire.provenance.sourceAuthority?.sourceAuthorityCommit ?? 'unknown';
const header = `// Generated by tools/wheel-mode5-e1-write-annular-native-header.mjs\n// Diagnostic-only E1 profile. Do not hand edit or treat as product authority.\n#pragma once\n\nstatic constexpr int E1_ANNULAR_STATION_COUNT = ${STATION_COUNT};\nstatic constexpr int E1_ANNULAR_ANGULAR_SEGMENTS = 64;\nstatic constexpr int E1_ANNULAR_SOURCE_TRIANGLES = ${tire.provenance.triangleCount};\nstatic constexpr const char* E1_ANNULAR_MARKER_CONTRACT = "${tire.provenance.markerContract}";\nstatic constexpr const char* E1_ANNULAR_SOURCE_AUTHORITY_COMMIT = "${sourceCommit}";\n\n${emitArray('E1_ANNULAR_AXIAL', 'axial')}\n\n${emitArray('E1_ANNULAR_INNER', 'inner')}\n\n${emitArray('E1_ANNULAR_OUTER_P75', 'outer')}\n`;

await writeFile(outputPath, header, 'utf8');
console.log('E1_ANNULAR_NATIVE_HEADER', JSON.stringify({
  outputPath,
  stationCount: stations.length,
  angularSegments: 64,
  axialMin: stations[0].axial,
  axialMax: stations.at(-1).axial,
  innerMin: Math.min(...stations.map((s) => s.inner)),
  innerMax: Math.max(...stations.map((s) => s.inner)),
  outerMin: Math.min(...stations.map((s) => s.outer)),
  outerMax: Math.max(...stations.map((s) => s.outer)),
  provenance: tire.provenance,
}));
console.log('E1_ANNULAR_NATIVE_HEADER_OK');
